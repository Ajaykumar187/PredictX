import fs from 'fs';
const src = JSON.parse(fs.readFileSync('data/OpenAPIScripMaster.json', 'utf8'));
const out = { NSE: {}, BSE: {}, INDEX: {} };
const rank = (s) => (s.endsWith('-EQ') ? 0 : 1);
const seen = {};
for (const x of src) {
  if (x.instrumenttype === '' && (x.exch_seg === 'NSE' || x.exch_seg === 'BSE')) {
    const isNse = x.exch_seg === 'NSE';
    if (isNse && !/-(EQ|BE)$/.test(x.symbol)) continue;
    const key = (isNse ? x.symbol.replace(/-(EQ|BE)$/, '') : x.symbol).toUpperCase();
    const k = x.exch_seg + key;
    const r = isNse ? rank(x.symbol) : 0;
    if (seen[k] !== undefined && seen[k] <= r) continue;
    seen[k] = r;
    out[x.exch_seg][key] = [x.token, x.name];
  } else if (x.instrumenttype === 'AMXIDX' && (x.exch_seg === 'NSE' || x.exch_seg === 'BSE')) {
    out.INDEX[x.name.toUpperCase()] = [x.exch_seg, x.token];
    out.INDEX[x.symbol.toUpperCase()] = [x.exch_seg, x.token];
  }
}
fs.writeFileSync('src/server/angelMap.ts', '// AUTO-GENERATED by scripts/build-angel-map.mjs - do not edit\nconst angelMap: { NSE: Record<string, [string, string]>; BSE: Record<string, [string, string]>; INDEX: Record<string, [string, string]> } = ' + JSON.stringify(out) + ';\nexport default angelMap;\n');
console.log('NSE', Object.keys(out.NSE).length, 'BSE', Object.keys(out.BSE).length, 'INDEX', Object.keys(out.INDEX).length);

const MON = { JAN: '01', FEB: '02', MAR: '03', APR: '04', MAY: '05', JUN: '06', JUL: '07', AUG: '08', SEP: '09', OCT: '10', NOV: '11', DEC: '12' };
const opts = {};
for (const x of src) {
  if (x.exch_seg !== 'NFO' || (x.instrumenttype !== 'OPTIDX' && x.instrumenttype !== 'OPTSTK')) continue;
  const m = /^(\d{2})([A-Z]{3})(\d{4})$/.exec(x.expiry);
  if (!m) continue;
  const iso = `${m[3]}-${MON[m[2]]}-${m[1]}`;
  const strike = Math.round(Number(x.strike) / 100 * 100) / 100;
  const kind = x.symbol.endsWith('CE') ? 1 : x.symbol.endsWith('PE') ? 2 : 0;
  if (!kind) continue;
  const u = (opts[x.name] ||= { lot: Number(x.lotsize) || 0, e: {} });
  const e = (u.e[iso] ||= {});
  (e[strike] ||= [strike, '', ''])[kind] = x.token;
}
const compact = {};
for (const [name, u] of Object.entries(opts)) {
  compact[name] = { lot: u.lot, e: Object.fromEntries(Object.entries(u.e).map(([iso, s]) => [iso, Object.values(s).sort((a, b) => a[0] - b[0])])) };
}
fs.writeFileSync('src/server/angelOptionsMap.ts', '// AUTO-GENERATED by scripts/build-angel-map.mjs - do not edit\nexport type OptionMap = Record<string, { lot: number; e: Record<string, Array<[number, string, string]>> }>;\nconst angelOptionsMap: OptionMap = ' + JSON.stringify(compact) + ';\nexport default angelOptionsMap;\n');
console.log('Option underlyings', Object.keys(compact).length);
